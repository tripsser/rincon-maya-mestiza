CREATE TABLE entidades_fiscales
(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_inquilino UUID NOT NULL,
    rfc VARCHAR(13) NOT NULL,
    razon_social VARCHAR(200) NOT NULL,
    regimen_fiscal VARCHAR(120) NOT NULL,
