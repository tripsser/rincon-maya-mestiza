-- Entidades base para Identity, inquilinos, restaurantes y unidades operativas.
-- Convenciones:
--   - Tablas y columnas de dominio en espanol.
--   - Llaves foraneas con prefijo id_.
--   - Tablas internas de ASP.NET Identity conservan sus nombres esperados.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE "AspNetUsers"
(
    "Id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "UserName" VARCHAR(256) NULL,
    "NormalizedUserName" VARCHAR(256) NULL,
    "Email" VARCHAR(256) NULL,
    "NormalizedEmail" VARCHAR(256) NULL,
    "EmailConfirmed" BOOLEAN NOT NULL DEFAULT FALSE,
    "PasswordHash" TEXT NULL,
    "SecurityStamp" TEXT NULL,
    "ConcurrencyStamp" TEXT NULL,
    "PhoneNumber" TEXT NULL,
    "PhoneNumberConfirmed" BOOLEAN NOT NULL DEFAULT FALSE,
    "TwoFactorEnabled" BOOLEAN NOT NULL DEFAULT FALSE,
    "LockoutEnd" TIMESTAMP WITH TIME ZONE NULL,
    "LockoutEnabled" BOOLEAN NOT NULL DEFAULT TRUE,
    "AccessFailedCount" INTEGER NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "AspNetRoles"
(
    "Id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "Name" VARCHAR(256) NULL,
    "NormalizedName" VARCHAR(256) NULL,
    "ConcurrencyStamp" TEXT NULL
);

CREATE TABLE "AspNetUserClaims"
(
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" UUID NOT NULL,
    "ClaimType" TEXT NULL,
    "ClaimValue" TEXT NULL,
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId"
        FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE "AspNetUserLogins"
(
    "LoginProvider" TEXT NOT NULL,
    "ProviderKey" TEXT NOT NULL,
    "ProviderDisplayName" TEXT NULL,
    "UserId" UUID NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins"
        PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId"
        FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE "AspNetUserTokens"
(
    "UserId" UUID NOT NULL,
    "LoginProvider" TEXT NOT NULL,
    "Name" TEXT NOT NULL,
    "Value" TEXT NULL,
    CONSTRAINT "PK_AspNetUserTokens"
        PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId"
        FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE "AspNetRoleClaims"
(
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleId" UUID NOT NULL,
    "ClaimType" TEXT NULL,
    "ClaimValue" TEXT NULL,
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId"
        FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE "AspNetUserRoles"
(
    "UserId" UUID NOT NULL,
    "RoleId" UUID NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles"
        PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId"
        FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id")
        ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId"
        FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE inquilinos
(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'activo'
        CHECK (estado IN ('activo', 'inactivo', 'suspendido')),
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_inquilinos_codigo
        UNIQUE (codigo)
);

CREATE TABLE roles_inquilino
(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_inquilino UUID NOT NULL,
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_roles_inquilino_inquilinos
        FOREIGN KEY (id_inquilino)
        REFERENCES inquilinos(id),
    CONSTRAINT ux_roles_inquilino_inquilino_codigo
        UNIQUE (id_inquilino, codigo),
    CONSTRAINT ux_roles_inquilino_inquilino_nombre
        UNIQUE (id_inquilino, nombre)
);

CREATE TABLE permisos_inquilino
(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo VARCHAR(100) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    descripcion TEXT NOT NULL,
    CONSTRAINT ux_permisos_inquilino_codigo
        UNIQUE (codigo)
);

CREATE TABLE roles_inquilino_permisos
(
    id_rol_inquilino UUID NOT NULL,
    id_permiso_inquilino UUID NOT NULL,
    CONSTRAINT pk_roles_inquilino_permisos
        PRIMARY KEY (id_rol_inquilino, id_permiso_inquilino),
    CONSTRAINT fk_roles_inquilino_permisos_roles
        FOREIGN KEY (id_rol_inquilino)
        REFERENCES roles_inquilino(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_roles_inquilino_permisos_permisos
        FOREIGN KEY (id_permiso_inquilino)
        REFERENCES permisos_inquilino(id)
        ON DELETE CASCADE
);

CREATE TABLE asignaciones_inquilino
(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo VARCHAR(40) NOT NULL,
    id_usuario UUID NOT NULL,
    id_inquilino UUID NOT NULL,
    id_rol_inquilino UUID NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NULL,
    CONSTRAINT fk_asignaciones_inquilino_usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES "AspNetUsers" ("Id"),
    CONSTRAINT fk_asignaciones_inquilino_inquilinos
        FOREIGN KEY (id_inquilino)
        REFERENCES inquilinos(id),
    CONSTRAINT fk_asignaciones_inquilino_roles
        FOREIGN KEY (id_rol_inquilino)
        REFERENCES roles_inquilino(id),
    CONSTRAINT ux_asignaciones_inquilino_codigo
        UNIQUE (codigo),
    CONSTRAINT ux_asignaciones_inquilino_usuario_inquilino_rol
        UNIQUE (id_usuario, id_inquilino, id_rol_inquilino)
);

CREATE TABLE asignaciones_inquilino_permisos
(
    id_asignacion_inquilino UUID NOT NULL,
    id_permiso_inquilino UUID NOT NULL,
    permitido BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_asignaciones_inquilino_permisos
        PRIMARY KEY (id_asignacion_inquilino, id_permiso_inquilino),
    CONSTRAINT fk_asignaciones_inquilino_permisos_asignaciones
        FOREIGN KEY (id_asignacion_inquilino)
        REFERENCES asignaciones_inquilino(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_asignaciones_inquilino_permisos_permisos
        FOREIGN KEY (id_permiso_inquilino)
        REFERENCES permisos_inquilino(id)
        ON DELETE CASCADE
);

